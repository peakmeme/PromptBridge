import { TextChunker } from './src/main/TextChunker';

const longText = `
第一段：这是一段模拟的长文测试数据。在 AI 的 RAG 检索系统中，切片算法决定了最终输出的质量。如果切片过小，语义会丢失；如果切片过大，会超出 Token 限制。因此，合理的重叠区（Overlap）至关重要。重叠区就像是两块布料之间的缝合处，确保 AI 在检索时不会因为关键信息被拦腰切断而产生误解。

第二段：我们需要模拟一个超过 400 字的文本段落。这里是一段关于“ PromptBridge ”项目愿景的详细描述。PromptBridge 旨在为专业人士提供本地化的隐私记忆中枢。它不仅是一个存储工具，更是一个连接本地数据与云端大模型的桥接器。在法律、金融、审计等对隐私极度敏感的行业，数据安全是底线。我们的目标是实现“算力与隐私的完美解耦”。

第三段：让我们继续增加字数。想象一下，你在处理一份长达 50 页的审计报告。每一章、每一节都有其独特的上下文。如果简单的按字符数切分，可能会出现“ 2023 年公司利润为 1000 ”在第一块，“万元”在第二块的情况。这样的切分对 AI 来说是毁灭性的。通过 50 个字的重叠区，第一块的结尾会包含“ 2023 年公司利润为 1000 万元”，而第二块的开头也会包含“ 2023 年公司利润为 1000 万元”。这样，无论 AI 检索到哪一块，都能获得完整的语义。

第四段：这里是重叠区的关键测试区域。我们将在这里放入一些独特的文字，以便肉眼观察。比如这句：“ 关键业务长句绝对不能被拦腰切断，否则 AI 的智商就会掉到地板上。我们必须通过科学的重叠区算法来缝合上下文，确保检索出的片段是连贯且具有完整逻辑的。” 这段话应该会同时出现在第一个切片的末尾和第二个切片的开头。

第五段：最后的总结。一个好的切片算法不仅要考虑长度，还要考虑语义边界。优先在句号、换行符处切分是基本的常识。如果在一个段落中间强行切断，即便有重叠区，也可能会破坏原有的逻辑流。因此，我们的算法会优先寻找标点符号。

第六段：再次强调，切片算法的稳定性直接关系到 RAG 系统的鲁棒性。在未来的开发中，我们甚至可以引入更智能的 NLP 库来按段落或主题进行切分。但目前，基于标点符号和重叠区的规则算法是最稳健、最容易调试的选择。

第七段：测试结束。希望这段 1000 字的长文能够完美触发我们的重叠逻辑。现在请观察控制台输出的切片长度，以及第一块结尾和第二块开头的文字重叠情况。
`.repeat(2); // 复制一遍确保超过 1000 字

async function runTest() {
  console.log('--- [TextChunker 测试开始] ---');
  
  const chunks = TextChunker.chunk(longText, 400, 50);
  
  console.log(`切片总数: ${chunks.length}`);
  
  if (chunks.length > 1) {
    console.log('\n--- [切片 0 的最后 50 个字] ---');
    const last50_0 = chunks[0].slice(-50);
    console.log(last50_0);
    
    console.log('\n--- [切片 1 的开头 50 个字] ---');
    const first50_1 = chunks[1].slice(0, 50);
    console.log(first50_1);
    
    console.log('\n--- [重叠区比对结论] ---');
    if (last50_0.includes(first50_1) || first50_1.includes(last50_0) || last50_0 === first50_1) {
      console.log('✅ 重叠区验证通过：肉眼可见重复文字。');
    } else {
      console.log('⚠️ 重叠区可能未完全对齐，请肉眼核对上述文字内容。');
    }
  } else {
    console.log('❌ 文本太短，未产生切片。');
  }
  
  console.log('\n--- [测试结束] ---');
}

runTest();
